import type { EnemyKind } from './enemies';

/**
 * Описание уровня.
 *
 * Карта рисуется символами:
 *   #  стена
 *   .  пол
 *   P  старт героя
 *   K  осколок света (нужно собрать все, чтобы открыть выход)
 *   E  выход
 *
 * Чтобы добавить уровень, просто допиши ещё один объект в массив LEVELS.
 * Позже карты можно рисовать в редакторе Tiled и грузить через this.load.tilemapTiledJSON().
 */
export interface LevelDef {
  name: string;
  /** Базовая пауза между волнами спавна (сек). Со временем уменьшается. */
  spawnEvery: number;
  /** Максимум врагов одновременно. */
  maxEnemies: number;
  /** Сколько врагов просыпается, когда берёшь осколок. */
  shardAmbush: number;
  /** Кто водится на уровне и с каким весом (чем больше вес, тем чаще). */
  enemyMix: Array<[EnemyKind, number]>;
  map: string;
}

